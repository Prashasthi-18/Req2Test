"""Export helpers: Gherkin feature file, CSV of test cases, project zip."""
from __future__ import annotations

import csv
import io
import re
import zipfile
from pathlib import Path
from typing import Any


def _slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-") or "feature"


def to_gherkin(feature_name: str, criteria: list[dict], test_cases: list[dict]) -> str:
    """One Feature, one Scenario per test case, tagged with TC id, type and priority."""
    by_ac = {c["id"]: c for c in criteria}
    lines = [f"Feature: {feature_name}"]
    for c in criteria:
        lines.append(f"  # {c['id']}: {c['text']}")
    for tc in sorted(test_cases, key=lambda t: t["id"]):
        ac = by_ac.get(tc["criterion_id"], {})
        lines += [
            "",
            f"  @{tc['id']} @{tc['criterion_id']} @{tc['type']} @{tc.get('priority', 'P1')}",
            f"  Scenario: {tc['title']}",
        ]
        if ac:
            lines.append(f"    # Verifies {ac['id']}")
        steps = tc["steps"]
        for i, step in enumerate(steps):
            keyword = "Given" if i == 0 else ("When" if i == 1 else "And")
            lines.append(f"    {keyword} {step[0].lower() + step[1:] if step else step}")
        lines.append(f"    Then {tc['expected'][0].lower() + tc['expected'][1:]}")
    return "\n".join(lines) + "\n"


def to_csv(test_cases: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["ID", "Criterion", "Title", "Type", "Priority", "Steps", "Expected result"])
    for tc in sorted(test_cases, key=lambda t: t["id"]):
        steps = "\n".join(f"{i + 1}. {s}" for i, s in enumerate(tc["steps"]))
        w.writerow([tc["id"], tc["criterion_id"], tc["title"], tc["type"], tc.get("priority", ""), steps, tc["expected"]])
    return buf.getvalue()


def build_zip(run: dict[str, Any], run_dir: Path) -> bytes:
    """Zip the generated Playwright project plus Gherkin, CSV and a README."""
    result = run["result"] or {}
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for sub in ("tests", "pages"):
            for f in sorted((run_dir / sub).rglob("*")) if (run_dir / sub).exists() else []:
                if f.is_file():
                    zf.write(f, f.relative_to(run_dir).as_posix())
        for name in ("package.json", "playwright.config.ts", "tsconfig.json"):
            if (run_dir / name).exists():
                zf.write(run_dir / name, name)
        feature = result.get("feature_name", "Feature")
        zf.writestr(f"features/{_slug(feature)}.feature",
                    to_gherkin(feature, result.get("criteria", []), result.get("test_cases", [])))
        zf.writestr("test-cases.csv", to_csv(result.get("test_cases", [])))
        zf.writestr(
            "README.md",
            f"# {run['title']}\n\nGenerated by Req2Test Crew.\n\n"
            "```bash\nnpm install\nnpx playwright install chromium\nBASE_URL=<your app url> npx playwright test\n```\n"
            "\nThe selectors and sample data assume the labels, roles and test ids described in the test cases. "
            "Adjust the page objects in `pages/` to match your application.\n",
        )
    return buf.getvalue()
